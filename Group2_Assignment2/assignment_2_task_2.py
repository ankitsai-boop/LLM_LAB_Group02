def backward_pass(X, y, y_pred, Z1, A1, Z2, A2, W2, W3):

    # Number of training samples
    n = X.shape[0]

    # -----------------------------
    # Output layer
    # -----------------------------

    dZ3 = (2 / n) * (y_pred - y)

    dW3 = A2.T @ dZ3
    db3 = np.sum(dZ3, axis=0, keepdims=True)


    # -----------------------------
    # Second hidden layer
    # -----------------------------

    dA2 = dZ3 @ W3.T

    dZ2 = dA2 * relu_derivative(Z2)

    dW2 = A1.T @ dZ2
    db2 = np.sum(dZ2, axis=0, keepdims=True)


    # -----------------------------
    # First hidden layer
    # -----------------------------

    dA1 = dZ2 @ W2.T

    dZ1 = dA1 * relu_derivative(Z1)

    dW1 = X.T @ dZ1
    db1 = np.sum(dZ1, axis=0, keepdims=True)


    return dW1, db1, dW2, db2, dW3, db3

def backward_pass(X, y, y_pred, Z1, A1, Z2, A2, W2, W3):

    # Number of training samples
    n = X.shape[0]

    # -----------------------------
    # Output layer
    # -----------------------------

    dZ3 = (2 / n) * (y_pred - y)

    dW3 = A2.T @ dZ3
    db3 = np.sum(dZ3, axis=0, keepdims=True)


    # -----------------------------
    # Second hidden layer
    # -----------------------------

    dA2 = dZ3 @ W3.T

    dZ2 = dA2 * relu_derivative(Z2)

    dW2 = A1.T @ dZ2
    db2 = np.sum(dZ2, axis=0, keepdims=True)


    # -----------------------------
    # First hidden layer
    # -----------------------------

    dA1 = dZ2 @ W2.T

    dZ1 = dA1 * relu_derivative(Z1)

    dW1 = X.T @ dZ1
    db1 = np.sum(dZ1, axis=0, keepdims=True)


    return dW1, db1, dW2, db2, dW3, db3

def train_gradient_descent(X, y, learning_rate=0.01, epochs=1000):

    # Initialize parameters
    W1, b1, W2, b2, W3, b3 = initialize_parameters()

    # Store loss
    losses = []

    # Start timer
    start_time = time.time()

    for epoch in range(epochs):

        # -------------------------
        # Forward propagation
        # -------------------------

        y_pred, Z1, A1, Z2, A2 = forward_pass(
            X, W1, b1, W2, b2, W3, b3
        )

        # -------------------------
        # Calculate loss
        # -------------------------

        loss = mse_loss(y, y_pred)
        losses.append(loss)

        # -------------------------
        # Backpropagation
        # -------------------------

        dW1, db1, dW2, db2, dW3, db3 = backward_pass(
            X, y, y_pred,
            Z1, A1, Z2, A2,
            W2, W3
        )

        # -------------------------
        # Gradient descent update
        # -------------------------

        W1 -= learning_rate * dW1
        b1 -= learning_rate * db1

        W2 -= learning_rate * dW2
        b2 -= learning_rate * db2

        W3 -= learning_rate * dW3
        b3 -= learning_rate * db3

    # Total training time
    training_time = time.time() - start_time

    # Return everything needed later
    parameters = (W1, b1, W2, b2, W3, b3)

    return parameters, losses, training_time

