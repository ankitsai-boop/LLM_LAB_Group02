def forward_pass(X, W1, b1, W2, b2, W3, b3):

    # First hidden layer
    Z1 = X @ W1 + b1
    A1 = relu(Z1)

    # Second hidden layer
    Z2 = A1 @ W2 + b2
    A2 = relu(Z2)

    # Output layer
    Z3 = A2 @ W3 + b3

    # Linear output
    y_pred = Z3

    return y_pred, Z1, A1, Z2, A2

